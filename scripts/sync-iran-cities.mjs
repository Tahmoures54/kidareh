#!/usr/bin/env node
/**
 * Sync Iran cities from official sajaddp/list-of-cities-in-Iran (divisions through 1404)
 * Writes compact modules used by src/data/processed/iranCities.ts
 *
 * Usage: node scripts/sync-iran-cities.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const OUT0 = path.join(ROOT, "src/data/raw/rawIranCitiesCompact0.ts");
const OUT1 = path.join(ROOT, "src/data/raw/rawIranCitiesCompact1.ts");

const CITIES_URL =
  "https://raw.githubusercontent.com/sajaddp/list-of-cities-in-Iran/main/dist/json/cities-filtered.json";
const PROVINCES_URL =
  "https://raw.githubusercontent.com/sajaddp/list-of-cities-in-Iran/main/dist/json/provinces.json";

async function fetchJson(url) {
  const res = await fetch(url, {
    headers: { "User-Agent": "kidareh-sync-iran-cities" },
  });
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  return res.json();
}

function esc(s) {
  return JSON.stringify(String(s ?? ""));
}

function buildPart(provinces, label) {
  const lines = [
    `/** sajaddp cities-filtered 1404 ${label} — generated by scripts/sync-iran-cities.mjs */`,
    `export const ${label === "part 0" ? "RAW_PART_0" : "RAW_PART_1"}: { p: string; c: string[] }[] = [`,
  ];
  for (const row of provinces) {
    const cities = row.cities.map((n) => esc(n)).join(", ");
    lines.push(`  {p:${esc(row.province)},c:[${cities}]},`);
  }
  lines.push("];");
  lines.push("");
  return lines.join("\n");
}

async function main() {
  console.log("⬇️  Fetching official Iran cities (sajaddp / 1404)...");
  const [cities, provinces] = await Promise.all([
    fetchJson(CITIES_URL),
    fetchJson(PROVINCES_URL),
  ]);

  const provById = new Map(provinces.map((p) => [p.id, p]));
  const byProv = new Map();

  for (const c of cities) {
    const prov = provById.get(c.province_id);
    if (!prov) continue;
    const pfa = prov.name;
    if (!byProv.has(pfa)) byProv.set(pfa, new Set());
    byProv.get(pfa).add(c.name);
  }

  const rows = [...byProv.entries()]
    .sort((a, b) => a[0].localeCompare(b[0], "fa"))
    .map(([province, set]) => ({
      province,
      cities: [...set].sort((a, b) => a.localeCompare(b, "fa")),
    }));

  const total = rows.reduce((n, r) => n + r.cities.length, 0);
  const mid = Math.ceil(rows.length / 2);
  const part0 = rows.slice(0, mid);
  const part1 = rows.slice(mid);

  fs.mkdirSync(path.dirname(OUT0), { recursive: true });
  fs.writeFileSync(OUT0, buildPart(part0, "part 0"), "utf8");
  fs.writeFileSync(OUT1, buildPart(part1, "part 1"), "utf8");

  console.log(`✅ Wrote ${OUT0}`);
  console.log(`✅ Wrote ${OUT1}`);
  console.log(`   Provinces: ${rows.length}, Cities: ${total}`);
}

main().catch((err) => {
  console.error("❌ sync-iran-cities failed:", err.message || err);
  process.exit(1);
});
